Ten years had passed since the catastrophe that shattered his spiritual meridian. Ten long years of being ridiculed as a useless cripple by the inner sect disciples who once bowed before his genius.

"The Heavenly Path is ruthless, but the human heart is more ruthless still," Lin Feng muttered softly, closing his eyes as a faint golden warmth pulsed deep within his dantian.

