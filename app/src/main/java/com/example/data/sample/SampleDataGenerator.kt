"Young Master Lin!" a breathless voice echoed up the stone steps. It was little Xiao Rou, her cheeks flushed crimson against the biting mountain wind. She carried a steaming clay medicine pot with both hands.

"Xiao Rou, how many times have I told you not to climb the perilous cliff during the morning frost?" Lin Feng opened his eyes, a faint smile softening his otherwise stern features.

"The Second Elder reduced our medicinal herb quota again," Xiao Rou pouted, carefully setting the clay pot down upon a flat boulder. "He claims broken meridians cannot absorb hundred-year ginseng anyway, so giving it to us would be a waste of sect resources!"

